#!/usr/bin/env bash
set -Eeuo pipefail

if (( $# != 1 )); then
    printf 'Usage: %s IMAGE\n' "${0##*/}" >&2
    exit 2
fi

image="$1"
if [[ ! -f "$image" ]]; then
    printf 'Wallpaper image does not exist: %s\n' "$image" >&2
    exit 1
fi
if ! command -v magick >/dev/null 2>&1; then
    printf 'Cannot measure wallpaper brightness: ImageMagick magick is not installed.\n' >&2
    exit 127
fi

brightness="$(magick "$image" -auto-orient -resize '64x64!' -colorspace Gray \
    -format '%[fx:mean]' info:)"
if [[ ! "$brightness" =~ ^(0([.][0-9]+)?|1([.]0+)?)$ ]]; then
    printf 'ImageMagick returned an invalid brightness value for %s: %s\n' \
        "$image" "$brightness" >&2
    exit 1
fi

output="$HOME/.config/waybar/wallpaper-brightness.css"
mkdir -p -- "$(dirname -- "$output")"
temporary="$(mktemp "${output}.XXXXXX")"
trap 'rm -f -- "$temporary"' EXIT

if awk -v brightness="$brightness" 'BEGIN { exit !(brightness >= 0.62) }'; then
    cat > "$temporary" <<'CSS'
/* Bright wallpaper detected; use a fixed-size dark surface. */
@define-color waybar_group_background rgba(0, 0, 0, 0.72);
CSS
    printf 'Bright wallpaper (mean luminance %s): dark Waybar color selected.\n' \
        "$brightness"
else
    printf '/* Generated by Scripts/update-waybar-background.sh. */\n@define-color waybar_group_background rgba(255, 255, 255, 0.065);\n' \
        > "$temporary"
    printf 'Wallpaper brightness below threshold (mean luminance %s): default Waybar color selected.\n' \
        "$brightness"
fi

mv -f -- "$temporary" "$output"
trap - EXIT

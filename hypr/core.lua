-- Colors are regenerated by Matugen into the shared settings directory.
local function read_color(name, fallback)
    local path = os.getenv("HOME") .. "/.config/1f2l/colors/" .. name
    local file = io.open(path, "r")
    if not file then
        io.stderr:write("Could not read color file: " .. path .. "\n")
        return fallback
    end

    local value = file:read("*l")
    file:close()
    value = value and value:gsub("^#", "")
    if not value or not value:match("^%x%x%x%x%x%x$" ) then
        io.stderr:write("Invalid color in " .. path .. "\n")
        return fallback
    end

    return "rgba(" .. value .. "ff)"
end

